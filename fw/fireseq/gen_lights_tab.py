"""Generates lights_tab.h: lookup tables for the few library maths calls the Fire's chip is too slow at.

The STM32F401 has single-precision hardware for + - * / and sqrt, but powf / expf / sinf run as slow
software (measured on the Fire: PLASMA took 3163 us per 16 pads, FLAME spiked too). So lights.c uses a
polynomial sine and these tables, and lights_test.c / lights_vs_orc.py check them against the real maths.
  python3 gen_lights_tab.py > lights_tab.h
"""
import math


def fl(x):
    """A C float literal: always has a '.' or an exponent (a bare 0f / 1f is not valid C)."""
    t = f"{x:.9g}"
    return (t if any(ch in t for ch in ".e") else t + ".0") + "f"


def table(name, n, f, comment):
    vals = ", ".join(fl(f(i / (n - 1))) for i in range(n))
    lines = []
    row = []
    for v in vals.split(", "):
        row.append(v)
        if len(row) == 6:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    return f"/* {comment} */\nstatic const float {name}[{n}] = {{\n" + "\n".join(lines) + "\n};\n"


print("/* GENERATED by gen_lights_tab.py: do not edit by hand. */")
print("#ifndef LIGHTS_TAB_H\n#define LIGHTS_TAB_H\n")
print(table("TAB_POW055", 257, lambda x: x ** 0.55, "x^0.55 for x in 0..1 (FLAME's gamma)"))
print(table("TAB_POW16", 129, lambda x: x ** 1.6, "x^1.6 for x in 0..1 (COMET's tail)"))
print(table("TAB_EXPM55", 129, lambda x: math.exp(-5.5 * x), "exp(-5.5 x) for x in 0..1 (BEAT's pulse)"))
print("/* 2^(k/32) for k = 0..31 (the light speed knob: 2^((v-64)/32)) */")
sp = [fl(2 ** (k / 32)) for k in range(32)]
print("static const float TAB_SPEED32[32] = {\n" + "\n".join("    " + ", ".join(sp[i:i + 6]) + "," for i in range(0, 32, 6)) + "\n};\n")
print("#endif")
